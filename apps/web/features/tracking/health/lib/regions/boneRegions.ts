import type {
    BodyRegion,
    TissueType,
    RegionView,
    RegionSide,
} from '@/features/tracking/health/types/regions';

export function makeRegion(
    id: string,
    displayName: string,
    regionType: TissueType,
    view: RegionView,
    aliases: string[] = [],
    side: RegionSide = 'center',
    parentRegion?: string,
): BodyRegion {
    return {
        id,
        displayName,
        side,
        view,
        ...(parentRegion !== undefined ? { parentRegion } : {}),
        supportedTissueTypes: [regionType, 'general'],
        svgPathId: `rg-${id}`,
        aliases: [displayName.toLowerCase(), ...aliases],
    };
}

