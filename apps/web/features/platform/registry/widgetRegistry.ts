function widget(
    id: string,
    type: string,
    featureId: string,
    category: WidgetCategory,
    name: string,
    description: string,
    goals: WidgetDefinition['goals'],
    capabilities: WidgetDefinition['capabilities'],
    visualizations: WidgetDefinition['visualizations'],
    permissions: WidgetDefinition['permissions'] = [],
    betaState: WidgetDefinition['betaState'] = 'stable',
): WidgetDefinition {
    return {
        id,
        type,
        featureId,
        name,
        description,
        category,
        surfaces: ['dashboard', 'page'],
        capabilities,
        requirements: permissions.length > 0 ? ['consent'] : [],
        permissions,
        dataSources: ['supabase'],
        visualizations,
        sizePresets: ['sm', 'md', 'lg'],
        betaState,
        goals,
        actions: capabilities.map((capability) => {
            const action = {
                id: `${id}-${capability}`,
                label: capability,
                capability,
                betaState,
            };
            return permissions[0]
                ? { ...action, requiresConsent: permissions[0] }
                : action;
        }),
    };
}
