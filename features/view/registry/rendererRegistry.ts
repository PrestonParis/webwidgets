export function getRendererForMime(mimeType: string) {
    return (
        VIEW_RENDERERS.find((renderer) =>
            renderer.mimeTypes.includes(mimeType),
        ) ??
        VIEW_RENDERERS.find(
            (renderer) =>
                mimeType.startsWith('image/') && renderer.id === 'image',
        ) ??
        null
    );
}
