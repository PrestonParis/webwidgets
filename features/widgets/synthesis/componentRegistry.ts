import type { WidgetComponentCategory } from './widgetDefinitionSchema';

export interface ComponentRegistryEntry {
    id: string;
    name: string;
    category: WidgetComponentCategory;
    description: string;
    acceptedDataShape: string;
    requiredProps: string[];
    allowedProps: string[];
    preview: string;
    supportedLayouts: string[];
    supportedActions: string[];
    emptyState: string;
    loadingState: string;
    errorState: string;
    accessibilityNotes: string;
    previewSupport: boolean;
}

function comp(
    id: string,
    name: string,
    cat: WidgetComponentCategory,
    desc: string,
    shape: string,
    req: string[],
    allowed: string[],
    preview = '',
): ComponentRegistryEntry {
    return {
        id,
        name,
        category: cat,
        description: desc,
        acceptedDataShape: shape,
        requiredProps: req,
        allowedProps: allowed,
        preview,
        supportedLayouts: [
            'small_card',
            'dense_dashboard_card',
            'full_page_module',
            'panel',
        ],
        supportedActions: ['data.refresh', 'nav.open_detail'],
        emptyState: 'No data available',
        loadingState: 'Skeleton rows',
        errorState: 'Inline retry panel',
        accessibilityNotes:
            'Expose labels, values, and actions with semantic text.',
        previewSupport: true,
    };
}

